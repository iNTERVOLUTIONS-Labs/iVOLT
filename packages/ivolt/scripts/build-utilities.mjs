// Generates src/css/utilities.css from the finite matrix in utilities.config.mjs.
// Selectors are doubled (specificity 0,2,0) so utilities win over component modifiers
// in both the layered and the flat entry (ADR-019).
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { utilities, responsiveBreakpoints } from "./utilities.config.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export function emitUtilities() {
  const rule = (cls, decl) => `.${cls}.${cls} { ${decl}; }`;
  const out = ["/* GENERATED by scripts/build-utilities.mjs. Finite matrix, see API_CONTRACT §4. */"];
  out.push(
    ".iv-u-sr-only.iv-u-sr-only, .iv-u-sr-only-focusable.iv-u-sr-only-focusable:not(:focus):not(:focus-within) {",
    "  position: absolute !important; inline-size: 1px !important; block-size: 1px !important; padding: 0 !important; margin: -1px !important;",
    "  overflow: hidden !important; clip-path: inset(50%) !important; white-space: nowrap !important; border: 0 !important;",
    "}",
  );
  for (const u of utilities) out.push(rule(`iv-u-${u.name}`, u.decl));
  for (const bp of responsiveBreakpoints) {
    out.push(`@media (--iv-${bp}) {`);
    for (const u of utilities) if (u.responsive) out.push("  " + rule(`iv-u-${bp}-${u.name}`, u.decl));
    out.push("}");
  }
  return out.join("\n") + "\n";
}

const css = emitUtilities();
writeFileSync(resolve(root, "src/css/utilities.css"), css);
console.log(`utilities: ${utilities.length} base + ${utilities.filter((u) => u.responsive).length}×${responsiveBreakpoints.length} responsive`);
